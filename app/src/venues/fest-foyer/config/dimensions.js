/**
 * Точная высота потолка 2-го этажа Y(d) для любого d ∈ [−0,80; 20,22]:
 *  1) [−0,80 … 1,10]: линейный скат от 9,20 у витража ВБ3 до 8,50;
 *  2) [1,10 … 4,10]: строго горизонтальная полка 8,50 (5 панелей = 3,00 м, H5);
 *  3) [4,10 … 5,03]: наклонная подшивка вниз от 8,50 до 7,45 (разрез 1-1 ТХ3);
 *  4) [5,03 … 9,60]: строго горизонтальный атриум 7,45 (H4);
 *  5) [9,60 … 20,22]: плавный ровный скат от 7,45 до 6,37 у стены витрин (H3).
 */
export function foyerCeilY(d) {
  const C = FOYER.ceil2;
  const R = FOYER.room;
  const lerp = (a, b, t) => a + (b - a) * t;
  if (d <= R.dGlass2) return C.glassY;
  if (d <= C.shelfFromD) {
    return lerp(C.glassY, C.shelfY, (d - R.dGlass2) / (C.shelfFromD - R.dGlass2));
  }
  if (d <= C.rampFromD) return C.shelfY;
  if (d <= C.rampToD) {
    return lerp(C.shelfY, C.atriumY, (d - C.rampFromD) / (C.rampToD - C.rampFromD));
  }
  if (d <= C.bendD) return C.atriumY;
  if (d >= R.dWall2) return C.wallY;
  return lerp(C.atriumY, C.wallY, (d - C.bendD) / (R.dWall2 - C.bendD));
}

/**
 * Линия наклонного уступа кирпичных торцов d_step(Y) (M8): линейная через замеренные точки
 * d(3,00) = 3,35 и d(8,50) = 4,10; на 1-й этаж продолжается той же прямой (d(0) ≈ 2,94, d(2,53) ≈ 3,29).
 * Оконная зона торцов (расширение наружу на 0,30 м) — d < d_step(Y).
 */
export function foyerEndWallStepD(y) {
  const S = FOYER.endWallStep;
  const y0 = FOYER.room.y2;
  const y1 = FOYER.ceil2.shelfY;
  return S.dAt2fFloor + ((S.dAt2fCeil - S.dAt2fFloor) * (y - y0)) / (y1 - y0);
}

/**
 * Точная отметка низа потолочной фермы Q25/31 Y0(d):
 *  - оконная галерея d < 4,10: 8,00 (5,00 м над 2-м эт., T4b);
 *  - после вертикального опуска 1,00 м (4,10 ≤ d ≤ 9,60): 7,00 (4,00 м над 2-м эт., T4a);
 *  - наклонная галерея (9,60 < d < 19,10): линейно от 7,00 до 6,00;
 *  - у стены витрин d ≥ 19,10: 6,00 (3,00 м над 2-м эт., T3 / H3).
 */
export function foyerTrussY0(d) {
  const T = FOYER.trusses;
  if (d < T.stepD) return T.windowY0;
  if (d <= T.bendD) return T.atriumY0;
  if (d >= T.wallD) return T.wallY0;
  const t = (d - T.bendD) / (T.wallD - T.bendD);
  return T.atriumY0 + (T.wallY0 - T.atriumY0) * t;
}
