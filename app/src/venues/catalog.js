/** Склонение числа зрительских мест («390 мест», «102 места»). */
export function seatsLabel(n) {
  if (!n) return null;
  const m10 = n % 10, m100 = n % 100;
  const w = m10 === 1 && m100 !== 11 ? 'место' : m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20) ? 'места' : 'мест';
  return `${n} ${w}`;
}

