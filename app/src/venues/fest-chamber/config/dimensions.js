/** Пояса треугольной фермы в сечении на глубине d: { bottom: [[y, d1], [y, d2]], top: [[yTop, d]], h }. */
export function trussChordsAt(d, cfg = CHAMBER) {
  const T = cfg.trusses;
  const s = T.side, h = triHeight(s), y = T.bottomY;
  return {
    bottom: [[y, d - s / 2], [y, d + s / 2]],
    top: [[y + h, d]],
    h,
  };
}

/** Высота верха фермы (ось верхнего пояса + радиус трубы). */
export function trussTopY(cfg = CHAMBER) {
  return cfg.trusses.bottomY + triHeight(cfg.trusses.side) + cfg.trusses.tube / 2;
}

/** X вертикальных подвесов фермы [x0..x1] к потолку. */
export function hangerXsFor(x0, x1, cfg = CHAMBER) {
  const T = cfg.trusses;
  const a = x0 + T.hangerInset, b = x1 - T.hangerInset;
  const n = Math.max(1, Math.ceil((b - a) / T.hangerStep));
  return Array.from({ length: n + 1 }, (_, i) => a + ((b - a) * i) / n);
}

/** Уровень пола ряда r (0..6): ряд 1 (r=0) на 0,00 м, ряды 2–7 (r=1..6) на +0,25 … +1,50 м. */
export function rowFloorY(r, cfg = CHAMBER) {
  return r * cfg.hall.stepHeight;
}

/** Передняя кромка ступени ряда r (0..6). Для 1-го ряда (на планшете перед ступенью −0,45) — +0,35 м. */
export function rowFrontD(r, cfg = CHAMBER) {
  const H = cfg.hall;
  if (r <= 0) return H.firstStepD + 0.8; // +0,35 м: 1-й ряд стоит на уровне 0,00 м перед первой ступенью (−0,45)
  return H.firstStepD - (r - 1) * H.stepDepth;
}

/** Высота пола зала в точке (x, d) для расчёта падения лучей света. */
export function hallFloorY(d, x = 0, cfg = CHAMBER) {
  const H = cfg.hall;
  if (d >= H.firstStepD) return 0;
  // слева у входа (x < −4,85) до нижней ступени лестницы (d >= −4,15) пол на уровне 0,00 м
  if (x < H.tierX0 && d >= H.sideStairs.dStart) return 0;
  if (d <= H.topPlatformD1) return H.topPlatformY;
  const stepIdx = Math.min(5, Math.max(1, Math.ceil((H.firstStepD - d) / H.stepDepth)));
  return stepIdx * H.stepHeight;
}

