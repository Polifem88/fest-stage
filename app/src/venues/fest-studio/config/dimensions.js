export const dutyLights = STUDIO.duty.list;

/** Все врезные элементы потолка как прямоугольники [x0, x1, d0, d1] в плане (для проверки неперекрытия). */
export function ceilingItems() {
  const r = STUDIO.duty.r;
  const out = [];
  for (const p of STUDIO.duty.list) out.push({ kind: 'duty', x0: p.x - r, x1: p.x + r, d0: p.d - r, d1: p.d + r });
  for (const c of STUDIO.cassettes) {
    const h = c.size / 2;
    out.push({ kind: 'cassette', x0: c.x - h, x1: c.x + h, d0: c.d0, d1: c.d1 });
  }
  for (const df of STUDIO.diffusers) {
    const h = df.size / 2;
    out.push({ kind: 'diffuser', x0: df.x - h, x1: df.x + h, d0: df.d - h, d1: df.d + h });
  }
  return out;
}

/** Прямоугольники ферм [x0, x1, d0, d1] в плане для заданного яруса ('upper' | 'lower'). */
export function trussFootprints(level = 'upper') {
  const s = STUDIO.trusses.size / 2;
  const lines = STUDIO.trusses[level]?.lines || [];
  return lines.map((l) => (l.axis === 'd' ? [l.a0, l.a1, l.at - s, l.at + s] : [l.at - s, l.at + s, l.a0, l.a1]));
}
