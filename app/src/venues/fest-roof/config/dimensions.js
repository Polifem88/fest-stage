const EPS = 1e-9;
const inRect = (x, d, [x0, x1, d0, d1]) => x >= x0 - EPS && x <= x1 + EPS && d >= d0 - EPS && d <= d1 + EPS;

/** Ниша над сегментом B стены 9 (выше Y vent9.y) — часть объёма помещения. */
const V9 = ROOF.vent9;
export const NICHE9 = [V9.x0, V9.x1, V9.d0, V9.d1];
/** Контур для обрезки конструкций под потолком: пол помещения + ниша над стеной 9. */
export const CEIL_RECTS = [...ROOF.rects, NICHE9];

/** Точка (x, d) внутри помещения (на высоте y: выше 2,50 — с нишей над стеной 9). */
export function insideRoom(x, d, y = 0) {
  return ROOF.rects.some((r) => inRect(x, d, r)) || (y > V9.y && inRect(x, d, NICHE9));
}

/** Повороты стен на обходе: последовательные концы. Конец стены i (по обходу) = начало стены i+1. */
export function wallEnds(w) {
  return w.axis === 'x' ? [[w.at, w.a0], [w.at, w.a1]] : [[w.a0, w.at], [w.a1, w.at]];
}

/** Контур пола помещения многоугольником [x, d] по обходу стен (проём коридора закрыт по линии стены 13). */
export function roomPolygon() {
  const poly = [];
  let cur = null;
  const dist = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1]);
  for (const w of ROOF.walls) {
    let [a, b] = wallEnds(w);
    if (cur && dist(b, cur) < dist(a, cur)) [a, b] = [b, a];
    if (cur && dist(a, cur) > 1e-6) poly.push(cur); // конец предыдущей стены перед проёмом
    poly.push(a);
    cur = b;
  }
  // убрать точки, лежащие на прямой между соседями
  return poly.filter((p, i) => {
    const a = poly[(i + poly.length - 1) % poly.length], c = poly[(i + 1) % poly.length];
    return Math.abs((p[0] - a[0]) * (c[1] - a[1]) - (p[1] - a[1]) * (c[0] - a[0])) > 1e-9;
  });
}

/**
 * Преграды для расстановки зала [x0, x1, d0, d1] (в плане): колонны, ноги V-косынок (до Y 2,50), стойки ферм,
 * цоколи, короб 11, зоны 1,0 перед дверями и проёмом коридора, мольтон. Стены — контур rects.
 */
export const OBSTACLES = (() => {
  const o = [];
  const DOOR_ZONE = 1.0;
  for (const c of ROOF.columns) if (!c.embedded) o.push({ kind: 'колонна', r: R(c.x - c.w / 2, c.x + c.w / 2, c.d - c.w / 2, c.d + c.w / 2) });
  for (const v of ROOF.vFrames) {
    const hw = v.w / 2;
    for (const [face, dir] of [[v.faceA, -1], [v.faceB, 1]]) {
      const a = face, b = face + dir * v.node.off;
      o.push({ kind: 'нога V-косынки', r: R(v.x - hw, v.x + hw, Math.min(a, b), Math.max(a, b)) });
    }
  }
  const s = ROOF.trusses.size / 2;
  for (const l of ROOF.trusses.legs) o.push({ kind: 'стойка фермы', r: R(l.x - s, l.x + s, l.d - s, l.d + s) });
  for (const p of ROOF.plinths) o.push({ kind: 'цоколь', r: R(p.x0, p.x1, p.d0, p.d1) });
  const v11 = ROOF.vent11;
  o.push({ kind: 'короб 11', r: R(v11.x0, v11.x1, v11.d0, v11.d1) });
  const wall = (id) => ROOF.walls.find((w) => w.id === id && !w.part);
  for (const dr of ROOF.doors) {
    const w = wall(dr.wall);
    // зона — со стороны помещения: проверяем, куда от стены лежит пол
    const mid = (dr.a0 + dr.a1) / 2;
    if (w.axis === 'd') {
      const side = insideRoom(mid, w.at + 0.01) ? 1 : -1;
      o.push({ kind: `дверь ${dr.wall}`, r: R(dr.a0, dr.a1, Math.min(w.at, w.at + side * DOOR_ZONE), Math.max(w.at, w.at + side * DOOR_ZONE)) });
    } else {
      const side = insideRoom(w.at + 0.01, mid) ? 1 : -1;
      o.push({ kind: `дверь ${dr.wall}`, r: R(Math.min(w.at, w.at + side * DOOR_ZONE), Math.max(w.at, w.at + side * DOOR_ZONE), dr.a0, dr.a1) });
    }
  }
  const c = ROOF.corridor;
  o.push({ kind: 'проём коридора', r: R(c.x0, c.x1, c.d0 - DOOR_ZONE, c.d0) });
  const m = ROOF.molton;
  o.push({ kind: 'мольтон', r: R(m.x0, m.x1, m.d, m.d) });
  return o;
})();
